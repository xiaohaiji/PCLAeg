const { _electron: electron } = require('playwright');
const { Manager } = require('../src/core.cjs');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const root = path.join(__dirname, '..', '.test-data', `feed-ui-${Date.now()}`);
  const manager = new Manager(root); await manager.init();
  await manager.create({ name: 'Feed test', populate: dest => fs.writeFile(path.join(dest, 'aegisub.exe'), 'fixture') });
  const configFile = path.join(__dirname, '..', 'dist/win-unpacked/launcher-paths.json');
  let originalConfig; try { originalConfig = await fs.readFile(configFile); } catch {}
  await fs.writeFile(configFile, JSON.stringify({ dataRoot: root }));
  const desktop = await electron.launch({ executablePath: path.join(__dirname, '..', 'dist/win-unpacked/Aegisub Launcher.exe'), args: [], env: { ...process.env, PCLAEG_TEST_ROOT: root } });
  try {
    const page = await desktop.firstWindow(), errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.getByRole('heading', { name: '开始新的创作' }).waitFor();
    await page.locator('nav button[data-page="plugins"]').click();
    await page.getByRole('button', { name: '发现插件 · 64', exact: true }).waitFor();
    await page.getByRole('button', { name: '添加插件源', exact: true }).click();
    await page.locator('dialog[open]').waitFor();
    assert.equal(await page.locator('#modal-title').innerText(), '添加插件源');
    assert.equal(await page.locator('#modal-input').inputValue(), '');
    assert.equal(await page.locator('#source-type option').count(), 5);
    await fs.mkdir(path.join(__dirname, '..', 'dist/screenshots'), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, '..', 'dist/screenshots/add-source-0.1.10.png') });
    await page.locator('#modal-input').fill('https://raw.githubusercontent.com/TypesettingTools/arch1t3cht-Aegisub-Scripts/main/DependencyControl.json');
    await page.locator('#modal-form button[type="submit"]').click();
    await page.locator('.feed-list:not(.known-feed-list)').waitFor({ timeout: 45000 });
    assert.match(await page.locator('.feed-list:not(.known-feed-list)').innerText(), /arch1t3cht/);
    await page.locator('.known-feed-list').waitFor();
    const associations = await page.evaluate(async () => (await window.launcher.command('state')).data);
    assert.ok(associations.discoveredFeeds.length >= 3);
    assert.equal(associations.pluginFeeds.length, 1);
    await page.getByRole('button', { name: '发现关联源', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.known-feed-list .settings-row').length > 3, { timeout: 45000 });
    const discovered = await page.evaluate(async () => (await window.launcher.command('state')).data);
    assert.ok(discovered.feedDiscoveryStatus.requested > 3); assert.equal(discovered.pluginFeeds.length, 1);
    const candidate = associations.discoveredFeeds[0];
    await page.locator(`[data-action="plugin-feed-known-add"][data-url="${candidate.url}"]`).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached', timeout: 45000 });
    const added = await page.evaluate(async () => (await window.launcher.command('state')).data);
    assert.equal(added.pluginFeeds.length, 2, await page.locator('#toast').innerText());
    await page.locator(`[data-action="plugin-feed-remove"][data-url="${candidate.url}"]`).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached' });
    await page.locator('#plugin-search').fill('Focus Lines');
    await page.getByRole('button', { name: '搜索', exact: true }).click();
    assert.equal(await page.locator('.plugin-card').count(), 1);
    await page.getByRole('button', { name: '安装到此实例', exact: true }).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached', timeout: 45000 });
    const state = await page.evaluate(async () => (await window.launcher.command('state')).data);
    const plugin = state.instances[0].plugins.find(p => p.namespace === 'arch.FocusLines');
    assert.ok(plugin, await page.locator('#toast').innerText());
    const appRoot = path.join(root, 'versions', state.instances[0].folder);
    await fs.access(path.join(appRoot, 'automation/include/l0/DependencyControl.moon'));
    const config = JSON.parse(await fs.readFile(path.join(appRoot, 'config/l0.DependencyControl.json')));
    assert.equal(config.macros['arch.FocusLines'].userFeed, state.pluginFeeds[0].url);
    await page.getByRole('button', { name: '移除源', exact: true }).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached' });
    const after = await page.evaluate(async () => (await window.launcher.command('state')).data);
    assert.equal(after.catalog.length, 64);
    assert.ok(after.instances[0].plugins.find(p => p.id === plugin.id));
    await page.getByRole('button', { name: '添加插件源', exact: true }).click();
    await page.locator('#modal-input').fill('https://github.com/TypesettingTools/unanimated-Aegisub-Scripts');
    await page.locator('#source-type').selectOption('github');
    await page.locator('#modal-form button[type="submit"]').click();
    await page.locator('.feed-list:not(.known-feed-list)').waitFor({ timeout: 45000 });
    await page.getByRole('button', { name: '刷新源', exact: true }).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached', timeout: 45000 });
    const github = await page.evaluate(async () => (await window.launcher.command('state')).data);
    assert.equal(github.pluginFeeds[0].type, 'github'); assert.equal(github.catalog.length, 88);
    await page.locator('#plugin-search').fill('ua.ChangeCase.lua');
    const sourceCard = page.locator('.plugin-card').filter({ hasText: '插件源' });
    assert.equal(await sourceCard.count(), 1);
    await sourceCard.getByRole('button', { name: '安装到此实例', exact: true }).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached', timeout: 45000 });
    const generic = await page.evaluate(async () => (await window.launcher.command('state')).data);
    const genericPlugin = generic.instances[0].plugins.find(p => p.file === 'ua.ChangeCase.lua');
    assert.ok(genericPlugin?.sourcePlugin, await page.locator('#toast').innerText());
    assert.equal(genericPlugin.feedType, 'github');
    await page.getByRole('button', { name: '移除源', exact: true }).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached' });
    await page.locator('[data-action="plugin-tab"][data-tab="installed"]').click();
    await page.locator('#plugin-search').fill('ua.ChangeCase.lua');
    await page.getByRole('button', { name: '更新', exact: true }).click();
    await page.locator('#task.hidden').waitFor({ state: 'attached', timeout: 45000 });
    const updated = await page.evaluate(async () => (await window.launcher.command('state')).data);
    assert.equal(updated.pluginFeeds.length, 0); assert.ok(updated.instances[0].plugins.find(p => p.id === genericPlugin.id));
    await page.locator('nav button[data-page="downloads"]').click();
    await page.locator('.version-row').first().waitFor({ timeout: 45000 });
    await page.screenshot({ path: path.join(__dirname, '..', 'dist/screenshots/downloads-0.1.10.png') });
    assert.deepEqual(errors, []);
    console.log('Packaged UI: generic source dialog, DependencyControl and GitHub sources, refresh, installation, update after source removal, and downloads passed.');
  } finally { await desktop.close(); if (originalConfig) await fs.writeFile(configFile, originalConfig); else await fs.rm(configFile, { force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
